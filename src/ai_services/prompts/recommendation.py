def get_recommendation_by_sentiment(sentiment: float) -> str:
    if -1.0 <= sentiment < -0.7:
        category = "EXTREME_NEGATIVITY_OR_EXHAUSTION"
    elif -0.7 <= sentiment < -0.4:
        category = "HIGH_STRESS_OR_IRRITATION"
    elif -0.4 <= sentiment < -0.1:
        category = "MILD_NEGATIVITY_OR_ROUTINE"
    elif -0.1 <= sentiment < 0.1:
        category = "NEUTRAL"
    elif 0.1 <= sentiment < 0.5:
        category = "MILD_POSITIVITY_OR_SATISFACTION"
    elif 0.5 <= sentiment <= 1.0:
        category = "STRONG_POSITIVITY_OR_INSPIRATION"
    else:
        return "Ошибка: sentiment вне диапазона [-1.0, 1.0]"
    return category
